/**
 * Generates the Java class for a project.
 *
 * Invariants:
 * - The formulas below must match `geometry.ts` exactly (see the note there).
 * - Region checks must not allocate, because robot code calls them every loop.
 * - Output is deterministic, with no timestamps, so regenerating produces clean diffs.
 * - Text from project files is never written into code unless validated or sanitized first.
 */
import { EDGE_TOLERANCE_METERS, rectRotation } from './geometry';
import type { JavaProfile } from './javaProfiles';
import { toMethodName, validateProject } from './model';
import { shapeOutline } from './shapeOps';
import type { Region, RegionProject, Shape, ValidationIssue } from './model';

/**
 * First line of every generated file. The app refuses to overwrite a file without it, so it can't
 * replace code someone wrote by hand.
 */
export const GENERATED_HEADER = '// GENERATED by RegionBool. Do not edit.';

/** Thrown when a project with validation errors is passed to {@link generateJava}. */
export class InvalidProjectError extends Error {
  constructor(readonly issues: readonly ValidationIssue[]) {
    super(`Can't generate code: ${issues.map((issue) => issue.message).join(' ')}`);
    this.name = 'InvalidProjectError';
  }
}

/**
 * Formats a number as a Java double literal. JavaScript prints the shortest text that reads back
 * as the same double, so the Java constant has exactly the value used by the preview.
 */
export function javaDouble(value: number): string {
  if (Object.is(value, -0)) return '-0.0';
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
}

/**
 * Makes a region name safe for a Java comment. Keeps only plain ASCII so nothing can end the comment
 * and file encoding can't matter, which also removes backslashes: Java reads unicode escapes like
 * `\\u000a` even inside comments.
 */
function commentSafe(name: string): string {
  return name
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .replace(/[^A-Za-z0-9 _.,()-]/g, '')
    .trim();
}

function polygonConstantName(regionIndex: number, shapeIndex: number, axis: 'X' | 'Y'): string {
  return `POLYGON_${regionIndex}_${shapeIndex}_${axis}`;
}

function shapeCall(shape: Shape, regionIndex: number, shapeIndex: number): string {
  const d = javaDouble;
  switch (shape.kind) {
    case 'rect': {
      const { cos, sin } = rectRotation(shape);
      return `inRect(x, y, ${d(shape.cx)}, ${d(shape.cy)}, ${d(shape.width / 2)}, ${d(shape.height / 2)}, ${d(cos)}, ${d(sin)})`;
    }
    case 'circle':
      return `inCircle(x, y, ${d(shape.cx)}, ${d(shape.cy)}, ${d(shape.radius)})`;
    case 'triangle':
    case 'polygon':
      return `inPolygon(x, y, ${polygonConstantName(regionIndex, shapeIndex, 'X')}, ${polygonConstantName(regionIndex, shapeIndex, 'Y')})`;
  }
}

function regionExpression(region: Region, regionIndex: number): string {
  const calls = (mode: Shape['mode']) =>
    region.shapes.flatMap((shape, shapeIndex) =>
      shape.mode === mode ? [shapeCall(shape, regionIndex, shapeIndex)] : [],
    );
  const adds = calls('add').join('\n        || ');
  const holes = calls('subtract');
  if (holes.length === 0) return adds;
  return `(${adds})\n        && !(${holes.join('\n            || ')})`;
}

function regionMethods(project: RegionProject, region: Region, regionIndex: number): string {
  const method = toMethodName(region.name);
  const name = commentSafe(region.name);
  const flips = region.allianceMode === 'alliance-relative';
  const allianceDoc = flips
    ? "Alliance-relative: drawn from blue's side and flipped when on red. An unknown alliance counts as blue."
    : 'Field-fixed: the same physical area on both alliances.';
  const flipY =
    project.field.symmetry === 'rotational' ? '\n      y = FIELD_WIDTH_METERS - y;' : '';
  const flipBlock = flips
    ? `\n    if (isRedAlliance()) {\n      x = FIELD_LENGTH_METERS - x;${flipY}\n    }`
    : '';
  return `  /**
   * Returns whether a robot pose is inside the region "${name}".
   *
   * <p>${allianceDoc}
   */
  public static boolean ${method}(Pose2d pose) {
    return ${method}(pose.getTranslation());
  }

  /**
   * Returns whether a point is inside the region "${name}".
   *
   * <p>${allianceDoc}
   */
  public static boolean ${method}(Translation2d point) {
    double x = point.getX();
    double y = point.getY();${flipBlock}
    return ${regionExpression(region, regionIndex)};
  }`;
}

const IN_RECT = `  private static boolean inRect(
      double x, double y, double cx, double cy, double halfWidth, double halfHeight, double cos, double sin) {
    double dx = x - cx;
    double dy = y - cy;
    double localX = dx * cos + dy * sin;
    double localY = dy * cos - dx * sin;
    return Math.abs(localX) <= halfWidth + EDGE_TOLERANCE && Math.abs(localY) <= halfHeight + EDGE_TOLERANCE;
  }`;

const IN_CIRCLE = `  private static boolean inCircle(double x, double y, double cx, double cy, double radius) {
    double dx = x - cx;
    double dy = y - cy;
    double limit = radius + EDGE_TOLERANCE;
    return dx * dx + dy * dy <= limit * limit;
  }`;

const IN_POLYGON = `  private static boolean inPolygon(double x, double y, double[] xs, double[] ys) {
    boolean inside = false;
    for (int i = 0, j = xs.length - 1; i < xs.length; j = i++) {
      double xi = xs[i];
      double yi = ys[i];
      double xj = xs[j];
      double yj = ys[j];
      double edgeX = xj - xi;
      double edgeY = yj - yi;
      double cross = (x - xi) * edgeY - (y - yi) * edgeX;
      boolean onLine = cross * cross <= EDGE_TOLERANCE * EDGE_TOLERANCE * (edgeX * edgeX + edgeY * edgeY);
      if (onLine
          && x >= Math.min(xi, xj) - EDGE_TOLERANCE
          && x <= Math.max(xi, xj) + EDGE_TOLERANCE
          && y >= Math.min(yi, yj) - EDGE_TOLERANCE
          && y <= Math.max(yi, yj) + EDGE_TOLERANCE) {
        return true;
      }
      if ((yi > y) != (yj > y) && x < (edgeX * (y - yi)) / edgeY + xi) {
        inside = !inside;
      }
    }
    return inside;
  }`;

function field2dMethods(project: RegionProject, usesAlliance: boolean): string {
  const d = javaDouble;
  const array = (values: number[]) => `new double[] {${values.map(d).join(', ')}}`;
  const calls = project.regions.flatMap((region) =>
    region.shapes.map((shape, shapeIndex) => {
      const hole = shape.mode === 'subtract' ? ' (hole)' : '';
      const name = `"${toMethodName(region.name)} ${shapeIndex}${hole}"`;
      const outline = shapeOutline(shape);
      const flip = usesAlliance
        ? region.allianceMode === 'alliance-relative'
          ? 'red, '
          : 'false, '
        : '';
      return `    publishOutline(field, ${name}, ${flip}${array(outline.map((p) => p.x))}, ${array(outline.map((p) => p.y))});`;
    }),
  );
  const flipY =
    project.field.symmetry === 'rotational' ? '\n        y = FIELD_WIDTH_METERS - y;' : '';
  const flipBlock = usesAlliance
    ? `\n      if (flip) {\n        x = FIELD_LENGTH_METERS - x;${flipY}\n      }`
    : '';
  return `  /**
   * Draws every region on a Field2d, so it shows in AdvantageScope, Glass or Elastic. Each shape
   * becomes one object, and circles are approximated. This allocates, so call it at startup or when
   * the alliance changes, not every loop. Shapes that flip use the alliance at the time of the call.
   */
  public static void publishTo(Field2d field) {${usesAlliance ? '\n    boolean red = isRedAlliance();' : ''}
${calls.join('\n')}
  }

  private static void publishOutline(
      Field2d field, String name, ${usesAlliance ? 'boolean flip, ' : ''}double[] xs, double[] ys) {
    Pose2d[] poses = new Pose2d[xs.length + 1];
    for (int i = 0; i < poses.length; i++) {
      double x = xs[i % xs.length];
      double y = ys[i % ys.length];${flipBlock}
      poses[i] = new Pose2d(x, y, new Rotation2d());
    }
    field.getObject(name).setPoses(poses);
  }`;
}

/**
 * Generates the Java source for a project, using the imports and calls of the given WPILib profile.
 *
 * @throws InvalidProjectError if the project has validation errors.
 */
export function generateJava(project: RegionProject, profile: JavaProfile): string {
  const errors = validateProject(project).filter((issue) => issue.severity === 'error');
  if (errors.length > 0) throw new InvalidProjectError(errors);

  const { regions, field, output } = project;
  const shapes = regions.flatMap((region) => region.shapes);
  const usesAlliance = regions.some((region) => region.allianceMode === 'alliance-relative');
  const usesRotationalFlip = usesAlliance && field.symmetry === 'rotational';

  const imports = [
    ...profile.geometryImports,
    ...profile.field2dImports,
    ...(usesAlliance ? profile.allianceImports : []),
  ]
    .sort()
    .map((name) => `import ${name};`);

  const constants: string[] = [
    `  private static final double EDGE_TOLERANCE = ${javaDouble(EDGE_TOLERANCE_METERS)};`,
  ];
  if (usesAlliance) {
    constants.push(
      `  private static final double FIELD_LENGTH_METERS = ${javaDouble(field.lengthMeters)};`,
    );
  }
  if (usesRotationalFlip) {
    constants.push(
      `  private static final double FIELD_WIDTH_METERS = ${javaDouble(field.widthMeters)};`,
    );
  }
  regions.forEach((region, regionIndex) => {
    region.shapes.forEach((shape, shapeIndex) => {
      if (shape.kind !== 'triangle' && shape.kind !== 'polygon') return;
      const array = (values: number[]) => `{${values.map(javaDouble).join(', ')}}`;
      constants.push(
        `  private static final double[] ${polygonConstantName(regionIndex, shapeIndex, 'X')} = ${array(shape.points.map((point) => point.x))};`,
        `  private static final double[] ${polygonConstantName(regionIndex, shapeIndex, 'Y')} = ${array(shape.points.map((point) => point.y))};`,
      );
    });
  });

  const helpers: string[] = [];
  if (usesAlliance) {
    helpers.push(
      `  private static boolean isRedAlliance() {\n    return ${profile.isRedExpression};\n  }`,
    );
  }
  if (shapes.some((shape) => shape.kind === 'rect')) helpers.push(IN_RECT);
  if (shapes.some((shape) => shape.kind === 'circle')) helpers.push(IN_CIRCLE);
  if (shapes.some((shape) => shape.kind === 'triangle' || shape.kind === 'polygon')) {
    helpers.push(IN_POLYGON);
  }

  const members = [
    constants.join('\n'),
    `  private ${output.className}() {}`,
    ...regions.map((region, index) => regionMethods(project, region, index)),
    field2dMethods(project, usesAlliance),
    ...helpers,
  ];

  return `${GENERATED_HEADER}
// Source: .regionbool/regions.json

package ${output.packageName};

${imports.join('\n')}

/** Field regions drawn in RegionBool. Coordinates are WPILib field coordinates in meters. */
public final class ${output.className} {
${members.join('\n\n')}
}
`;
}
